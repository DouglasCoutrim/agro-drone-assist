CREATE TABLE public.pedidos_compra (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  numero integer GENERATED BY DEFAULT AS IDENTITY,
  setor text NOT NULL DEFAULT 'estoque',
  titulo text NOT NULL DEFAULT '',
  observacoes text NOT NULL DEFAULT '',
  solicitado_por uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.pedidos_compra TO authenticated;
GRANT ALL ON public.pedidos_compra TO service_role;
ALTER TABLE public.pedidos_compra ENABLE ROW LEVEL SECURITY;
CREATE POLICY pedidos_leitura ON public.pedidos_compra FOR SELECT TO authenticated USING (organization_id = public.get_user_org_id(auth.uid()));
CREATE POLICY pedidos_criacao ON public.pedidos_compra FOR INSERT TO authenticated WITH CHECK (organization_id = public.get_user_org_id(auth.uid()) AND public.is_admin_or_tecnico(auth.uid()));
CREATE POLICY pedidos_edicao ON public.pedidos_compra FOR UPDATE TO authenticated USING (organization_id = public.get_user_org_id(auth.uid()) AND (public.has_role(auth.uid(),'admin') OR solicitado_por = auth.uid())) WITH CHECK (organization_id = public.get_user_org_id(auth.uid()));
CREATE POLICY pedidos_exclusao ON public.pedidos_compra FOR DELETE TO authenticated USING (organization_id = public.get_user_org_id(auth.uid()) AND (public.has_role(auth.uid(),'admin') OR solicitado_por = auth.uid()));

ALTER TABLE public.solicitacoes_compra ADD COLUMN pedido_id uuid REFERENCES public.pedidos_compra(id) ON DELETE CASCADE;
ALTER TABLE public.solicitacoes_compra ADD COLUMN setor text NOT NULL DEFAULT 'estoque';
CREATE INDEX idx_solic_pedido ON public.solicitacoes_compra(pedido_id);
CREATE POLICY solic_edicao_solicitante ON public.solicitacoes_compra FOR UPDATE TO authenticated
  USING (organization_id = public.get_user_org_id(auth.uid()) AND solicitado_por = auth.uid() AND status = 'pendente')
  WITH CHECK (organization_id = public.get_user_org_id(auth.uid()) AND solicitado_por = auth.uid() AND status = 'pendente');

ALTER TABLE public.itens_estoque ADD COLUMN imagem_url text;